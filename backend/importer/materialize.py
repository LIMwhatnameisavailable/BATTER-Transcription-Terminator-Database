"""Build a deterministic, database-shaped BTED staging bundle.

The bundle is an auditable intermediate representation, not a PostgreSQL
dump.  It is built only after :mod:`backend.importer.canonical` has validated
the canonical release and the reference-contig registry.  No database driver,
network request, or biological interpretation is involved here.

Every table is written as UTF-8 JSONL with stable key ordering.  Identity
columns generated by PostgreSQL are represented by explicit ``*_ref`` natural
keys so that a future writer can resolve foreign keys in a transaction.
"""

