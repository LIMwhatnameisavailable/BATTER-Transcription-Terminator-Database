class MaterializationError(RuntimeError):
    """Raised when a validated release cannot be safely materialized."""


@dataclass(frozen=True)
class MaterializationResult:
    """Result of a successful staging-bundle build."""

    output_dir: Path
    manifest: dict[str, Any]

    @property
    def table_counts(self) -> dict[str, int]:
        return {
            name: int(value.get("row_count", 0))
            for name, value in self.manifest.get("tables", {}).items()
        }


def _utc_timestamp(value: str | None) -> str:
    if value is None:
        parsed = datetime.now(timezone.utc)
    else:
        raw = str(value).strip()
        try:
            parsed = datetime.fromisoformat(raw.replace("Z", "+00:00"))
        except ValueError as exc:
            raise MaterializationError(
                "generated_at_utc must be ISO-8601 with an explicit timezone"
            ) from exc
        if parsed.tzinfo is None:
            raise MaterializationError(
                "generated_at_utc must include a timezone (for example, Z)"
            )
    parsed = parsed.astimezone(timezone.utc).replace(microsecond=0)
    return parsed.isoformat().replace("+00:00", "Z")


def _validate_origin_base(value: str) -> tuple[str, str]:
    raw = str(value or "").strip()
    parsed = urlparse(raw)
    if parsed.scheme != "https" or not parsed.hostname:
        raise MaterializationError("asset_origin_base must be an HTTPS URL with a hostname")
    if parsed.username or parsed.password or parsed.query or parsed.fragment:
        raise MaterializationError(
            "asset_origin_base must not contain credentials, query parameters, or fragments"
        )
    base = raw.rstrip("/")
    return base, parsed.hostname


def _int(value: Any, field: str) -> int:
    try:
        return int(str(value))
    except (TypeError, ValueError) as exc:
        raise MaterializationError(f"{field} must be an integer: {value!r}") from exc


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _write_jsonl(path: Path, rows: Iterable[Mapping[str, Any]]) -> tuple[int, str, int]:
    count = 0
    digest = hashlib.sha256()
    size = 0
    with path.open("wb") as handle:
        for row in rows:
            payload = (
                json.dumps(
                    dict(row),
                    ensure_ascii=False,
                    sort_keys=True,
                    separators=(",", ":"),
                ).encode("utf-8")
                + b"\n"
            )
            handle.write(payload)
            digest.update(payload)
            size += len(payload)
            count += 1
    return count, digest.hexdigest(), size


def _json_file(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise MaterializationError(f"cannot read JSON metadata: {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise MaterializationError(f"JSON metadata must be an object: {path}")
    return value


