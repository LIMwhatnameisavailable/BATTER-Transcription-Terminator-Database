-- BTED v0.3 PostgreSQL schema skeleton
--
-- This DDL is a derived-query-layer contract.  It intentionally contains no
-- seed data and no DROP/TRUNCATE statements.  A future importer must load a
-- new release in staging, validate it, and switch the published release in a
-- transaction.  The canonical release under data/public remains the source
-- of truth.

BEGIN;

CREATE TABLE release_versions (
    release_version TEXT PRIMARY KEY,
    release_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    release_date DATE,
    canonical_manifest_path TEXT NOT NULL,
    canonical_manifest_sha256 TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'staged',
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT release_versions_release_id_uq UNIQUE (release_id),
    CONSTRAINT release_versions_version_ck
        CHECK (release_version ~ '^v[0-9]+[.][0-9]+[.][0-9]+$'),
    CONSTRAINT release_versions_sha256_ck
        CHECK (canonical_manifest_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT release_versions_current_status_ck
        CHECK (NOT is_current OR status = 'published'),
    CONSTRAINT release_versions_status_ck
        CHECK (status IN ('staged', 'validated', 'published', 'retired'))
);

CREATE UNIQUE INDEX release_versions_one_current_idx
    ON release_versions (is_current)
    WHERE is_current;

CREATE TABLE import_runs (
    import_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_version TEXT NOT NULL
        REFERENCES release_versions (release_version) ON DELETE RESTRICT,
    importer_name TEXT NOT NULL,
    importer_version TEXT NOT NULL,
    input_manifest_path TEXT NOT NULL,
    input_manifest_sha256 TEXT NOT NULL,
    staging_location TEXT,
    run_status TEXT NOT NULL DEFAULT 'staging',
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    validation_summary JSONB NOT NULL DEFAULT '{}'::jsonb,
    error_summary TEXT,
    committed_at TIMESTAMPTZ,
    CONSTRAINT import_runs_manifest_sha256_ck
        CHECK (input_manifest_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT import_runs_status_ck
        CHECK (run_status IN ('staging', 'validating', 'validated', 'committed', 'failed', 'aborted')),
    CONSTRAINT import_runs_time_ck
        CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE INDEX import_runs_release_status_idx
    ON import_runs (release_version, run_status);
CREATE INDEX import_runs_input_manifest_idx
    ON import_runs (release_version, input_manifest_sha256, started_at);

CREATE TABLE publications (
    publication_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pmid TEXT NOT NULL,
    doi TEXT,
    pmc TEXT,
    published_year SMALLINT,
    journal TEXT,
    paper_title TEXT NOT NULL,
    citation_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT publications_pmid_ck CHECK (pmid ~ '^[0-9]+$'),
    CONSTRAINT publications_year_ck
        CHECK (published_year IS NULL OR published_year BETWEEN 1800 AND 2200)
);

CREATE UNIQUE INDEX publications_pmid_uq ON publications (pmid);
CREATE UNIQUE INDEX publications_doi_lower_uq
    ON publications (lower(doi))
    WHERE doi IS NOT NULL;

CREATE TABLE assemblies (
    assembly_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assembly_accession TEXT NOT NULL,
    assembly_name TEXT,
    organism_name TEXT,
    strain TEXT,
    taxon_id INTEGER,
    reference_url TEXT,
    CONSTRAINT assemblies_accession_uq UNIQUE (assembly_accession),
    CONSTRAINT assemblies_accession_ck
        CHECK (assembly_accession ~ '^(GCA|GCF)_[0-9]+[.][0-9]+$')
);

CREATE TABLE contigs (
    contig_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assembly_id BIGINT NOT NULL
        REFERENCES assemblies (assembly_id) ON DELETE RESTRICT,
    contig_accession TEXT NOT NULL,
    contig_name TEXT NOT NULL,
    length_bp BIGINT NOT NULL,
    sequence_sha256 TEXT,
    CONSTRAINT contigs_length_ck CHECK (length_bp > 0),
    CONSTRAINT contigs_sha256_ck
        CHECK (sequence_sha256 IS NULL OR sequence_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT contigs_accession_uq UNIQUE (assembly_id, contig_accession),
    CONSTRAINT contigs_name_uq UNIQUE (assembly_id, contig_name),
    CONSTRAINT contigs_id_assembly_uq UNIQUE (contig_id, assembly_id)
);

CREATE INDEX contigs_assembly_idx ON contigs (assembly_id);

CREATE TABLE sources (
    source_pk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_version TEXT NOT NULL
        REFERENCES release_versions (release_version) ON DELETE RESTRICT,
    source_id TEXT NOT NULL,
    publication_id BIGINT NOT NULL
        REFERENCES publications (publication_id) ON DELETE RESTRICT,
    assembly_id BIGINT NOT NULL
        REFERENCES assemblies (assembly_id) ON DELETE RESTRICT,
    species TEXT NOT NULL,
    phylum TEXT,
    assay_family TEXT NOT NULL,
    release_status TEXT NOT NULL,
    evidence_class TEXT NOT NULL,
    redistribution_status TEXT NOT NULL,
    accessibility_status TEXT NOT NULL,
    coordinate_status TEXT NOT NULL,
    processing_status TEXT NOT NULL,
    -- Preserve the Table S1 spelling; API may expose a derived alias.
    used_for_batter_augmentation BOOLEAN NOT NULL,
    record_count INTEGER NOT NULL DEFAULT 0,
    has_jbrowse BOOLEAN NOT NULL DEFAULT FALSE,
    manifest_path TEXT NOT NULL,
    manifest_sha256 TEXT NOT NULL,
    record_root TEXT,
    source_note TEXT,
    decision_note TEXT,
    known_limitations TEXT,
    CONSTRAINT sources_release_source_uq UNIQUE (release_version, source_id),
    CONSTRAINT sources_release_pk_uq UNIQUE (release_version, source_pk),
    CONSTRAINT sources_record_count_ck CHECK (record_count >= 0),
    CONSTRAINT sources_manifest_sha256_ck
        CHECK (manifest_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT sources_status_ck
        CHECK (release_status IN ('published_standardized', 'audit_only', 'to_review', 'blocked')),
    CONSTRAINT sources_evidence_ck
        CHECK (evidence_class IN (
            'observed_signal',
            'called_endpoint',
            'author_called_endpoint',
            'curated_record',
            'author_integrated_mixed_evidence',
            'prediction_only',
            'NA'
        )),
    CONSTRAINT sources_public_state_ck
        CHECK (
            (
                release_status = 'published_standardized'
                AND record_count > 0
                AND evidence_class IN (
                    'observed_signal',
                    'called_endpoint',
                    'author_called_endpoint',
                    'curated_record'
                )
            )
            OR (
                release_status = 'audit_only'
                AND record_count = 0
                AND has_jbrowse = FALSE
                AND evidence_class = 'NA'
            )
            OR (
                release_status IN ('to_review', 'blocked')
                AND record_count = 0
                AND has_jbrowse = FALSE
            )
        )
);

CREATE INDEX sources_release_status_idx
    ON sources (release_version, release_status);
CREATE INDEX sources_assembly_idx ON sources (assembly_id);
CREATE INDEX sources_augmentation_idx
    ON sources (release_version, used_for_batter_augmentation)
    WHERE used_for_batter_augmentation;

CREATE TABLE source_accessions (
    source_accession_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_pk BIGINT NOT NULL
        REFERENCES sources (source_pk) ON DELETE RESTRICT,
    accession_namespace TEXT NOT NULL,
    accession TEXT NOT NULL,
    raw_value TEXT NOT NULL,
    accession_type TEXT NOT NULL,
    ordinal INTEGER,
    external_url TEXT,
    CONSTRAINT source_accessions_namespace_ck
        CHECK (accession_namespace ~ '^[A-Za-z0-9_]+$'),
    CONSTRAINT source_accessions_normalized_ck
        CHECK (accession = btrim(accession) AND accession !~ '[,;[:space:]]'),
    CONSTRAINT source_accessions_ordinal_ck
        CHECK (ordinal IS NULL OR ordinal > 0),
    CONSTRAINT source_accessions_uq
        UNIQUE (source_pk, accession_namespace, accession)
);

CREATE INDEX source_accessions_lookup_idx
    ON source_accessions (accession_namespace, accession);

CREATE TABLE samples (
    sample_pk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_pk BIGINT NOT NULL
        REFERENCES sources (source_pk) ON DELETE RESTRICT,
    sample_id TEXT NOT NULL,
    sample_label TEXT,
    biological_condition TEXT,
    replicate_label TEXT,
    sample_accession TEXT,
    metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT samples_id_ck CHECK (sample_id = btrim(sample_id) AND sample_id <> ''),
    CONSTRAINT samples_source_id_uq UNIQUE (source_pk, sample_id),
    CONSTRAINT samples_source_id_pk_uq UNIQUE (source_pk, sample_id, sample_pk)
);

CREATE TABLE endpoints (
    endpoint_pk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_version TEXT NOT NULL
        REFERENCES release_versions (release_version) ON DELETE RESTRICT,
    source_pk BIGINT NOT NULL,
    contig_id BIGINT NOT NULL
        REFERENCES contigs (contig_id) ON DELETE RESTRICT,
    sample_pk BIGINT NOT NULL
        REFERENCES samples (sample_pk) ON DELETE RESTRICT,

    -- The following 24 columns are the lossless v0.2 endpoints.tsv contract.
    end_id TEXT NOT NULL,
    source_id TEXT NOT NULL,
    sample_id TEXT NOT NULL,
    assay TEXT NOT NULL,
    evidence_class TEXT NOT NULL,
    author_endpoint_id TEXT NOT NULL,
    published_reference_accession TEXT NOT NULL,
    reference_assembly TEXT NOT NULL,
    reference_name TEXT NOT NULL,
    replicon_label TEXT NOT NULL,
    biological_coordinate_1based BIGINT NOT NULL,
    bed_start_0based BIGINT NOT NULL,
    bed_end_0based BIGINT NOT NULL,
    strand CHAR(1) NOT NULL,
    signal_or_score TEXT NOT NULL,
    author_category TEXT NOT NULL,
    associated_gene_or_locus TEXT NOT NULL,
    pmid TEXT NOT NULL,
    doi TEXT NOT NULL,
    source_table_or_file TEXT NOT NULL,
    coordinate_interpretation TEXT NOT NULL,
    original_row_reference TEXT NOT NULL,
    qc_status TEXT NOT NULL,
    note TEXT NOT NULL,

    CONSTRAINT endpoints_release_source_fk
        FOREIGN KEY (release_version, source_pk)
        REFERENCES sources (release_version, source_pk) ON DELETE RESTRICT,
    CONSTRAINT endpoints_sample_context_fk
        FOREIGN KEY (source_pk, sample_id, sample_pk)
        REFERENCES samples (source_pk, sample_id, sample_pk) ON DELETE RESTRICT,
    CONSTRAINT endpoints_release_pk_uq UNIQUE (release_version, endpoint_pk),
    CONSTRAINT endpoints_release_end_uq UNIQUE (release_version, end_id),
    CONSTRAINT endpoints_release_source_end_uq
        UNIQUE (release_version, source_pk, end_id),
    CONSTRAINT endpoints_evidence_ck
        CHECK (evidence_class IN (
            'observed_signal',
            'called_endpoint',
            'author_called_endpoint',
            'curated_record'
        )),
    CONSTRAINT endpoints_coordinate_ck
        CHECK (
            biological_coordinate_1based >= 1
            AND bed_start_0based >= 0
            AND bed_end_0based > bed_start_0based
            AND bed_start_0based = biological_coordinate_1based - 1
            AND bed_end_0based = biological_coordinate_1based
        ),
    CONSTRAINT endpoints_strand_ck CHECK (strand IN ('+', '-')),
    CONSTRAINT endpoints_pmid_ck CHECK (pmid ~ '^[0-9]+$')
);

CREATE INDEX endpoints_release_source_idx
    ON endpoints (release_version, source_pk, end_id);
CREATE INDEX endpoints_contig_position_idx
    ON endpoints (contig_id, biological_coordinate_1based, strand);
CREATE INDEX endpoints_release_evidence_idx
    ON endpoints (release_version, evidence_class);
CREATE INDEX endpoints_sample_idx ON endpoints (source_pk, sample_id);

CREATE TABLE source_annotations (
    annotation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_version TEXT NOT NULL
        REFERENCES release_versions (release_version) ON DELETE RESTRICT,
