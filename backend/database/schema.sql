CREATE FUNCTION bted_guard_gene_annotation() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_asset_sha256 TEXT;
    v_asset_kind TEXT;
BEGIN
    -- A circular-replicon gene end may exceed the linear FAI length; the
    -- gene end is validated for ordering in genes_coordinate_ck and retained.
    PERFORM 1
      FROM contigs AS c
     WHERE c.contig_id = NEW.contig_id
       AND c.assembly_id = NEW.assembly_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'gene contig does not belong to gene assembly';
    END IF;
    SELECT a.sha256, a.asset_kind
      INTO v_asset_sha256, v_asset_kind
      FROM assets AS a
     WHERE a.release_version = NEW.release_version
       AND a.asset_id = NEW.annotation_asset_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'gene annotation asset is not registered in this release';
    END IF;
    IF v_asset_kind <> 'gff3' THEN
        RAISE EXCEPTION 'gene annotation asset must be a registered GFF3 asset';
    END IF;
    IF v_asset_sha256 <> NEW.annotation_sha256 THEN
        RAISE EXCEPTION 'gene annotation checksum does not match registered asset';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER genes_annotation_guard
    BEFORE INSERT OR UPDATE ON genes
    FOR EACH ROW EXECUTE FUNCTION bted_guard_gene_annotation();

-- Public endpoints may never be prediction-only, mixed-evidence, audit-only,
-- to_review, or blocked rows.  The source/release/contig checks live here
-- because a plain CHECK cannot inspect a referenced row.
CREATE FUNCTION bted_guard_public_endpoint() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_source_id TEXT;
    v_release_status TEXT;
    v_source_evidence TEXT;
    v_source_assembly BIGINT;
    v_contig_assembly BIGINT;
    v_contig_length BIGINT;
    v_expected_assembly TEXT;
BEGIN
    IF NEW.evidence_class IN ('author_integrated_mixed_evidence', 'prediction_only') THEN
        RAISE EXCEPTION 'forbidden public endpoint evidence class: %', NEW.evidence_class;
    END IF;

    SELECT s.source_id, s.release_status, s.evidence_class, s.assembly_id
      INTO v_source_id, v_release_status, v_source_evidence, v_source_assembly
      FROM sources AS s
     WHERE s.release_version = NEW.release_version
       AND s.source_pk = NEW.source_pk;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'endpoint source/release does not exist: % / %',
            NEW.release_version, NEW.source_pk;
    END IF;
    IF v_source_id <> NEW.source_id THEN
        RAISE EXCEPTION 'endpoint source_id does not match sources.source_id';
    END IF;
    IF v_release_status <> 'published_standardized' THEN
        RAISE EXCEPTION 'endpoint cannot be attached to source status %', v_release_status;
    END IF;
    IF v_source_evidence IN ('author_integrated_mixed_evidence', 'prediction_only', 'NA') THEN
        RAISE EXCEPTION 'source evidence is not public endpoint evidence: %', v_source_evidence;
    END IF;

    SELECT c.assembly_id, c.length_bp
      INTO v_contig_assembly, v_contig_length
      FROM contigs AS c
     WHERE c.contig_id = NEW.contig_id;
    IF v_source_assembly IS DISTINCT FROM v_contig_assembly THEN
        RAISE EXCEPTION 'endpoint contig belongs to a different assembly';
    END IF;
    IF NEW.biological_coordinate_1based > v_contig_length THEN
        RAISE EXCEPTION 'endpoint position % exceeds contig length %',
            NEW.biological_coordinate_1based, v_contig_length;
    END IF;

    SELECT a.assembly_accession
      INTO v_expected_assembly
      FROM assemblies AS a
     WHERE a.assembly_id = v_source_assembly;
    IF v_expected_assembly <> NEW.reference_assembly THEN
        RAISE EXCEPTION 'endpoint reference_assembly does not match source assembly';
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM samples AS sm
         WHERE sm.sample_pk = NEW.sample_pk
           AND sm.source_pk = NEW.source_pk
           AND sm.sample_id = NEW.sample_id
    ) THEN
        RAISE EXCEPTION 'endpoint sample_pk/sample_id/source_pk do not match';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER endpoints_public_guard
    BEFORE INSERT OR UPDATE ON endpoints
    FOR EACH ROW EXECUTE FUNCTION bted_guard_public_endpoint();

CREATE FUNCTION bted_guard_source_state() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.release_status = 'audit_only'
       AND EXISTS (
           SELECT 1 FROM endpoints AS e
            WHERE e.release_version = OLD.release_version
              AND e.source_pk = OLD.source_pk
       ) THEN
        RAISE EXCEPTION 'audit_only source cannot retain endpoint rows';
    END IF;
    IF NEW.release_status <> 'published_standardized'
       AND NEW.has_jbrowse THEN
        RAISE EXCEPTION 'non-published source cannot expose JBrowse';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER sources_state_guard
    BEFORE UPDATE ON sources
    FOR EACH ROW EXECUTE FUNCTION bted_guard_source_state();

COMMENT ON TABLE release_versions IS
    'Versioned canonical release registry; PostgreSQL is a derived query layer.';
COMMENT ON TABLE endpoints IS
    'Public endpoint rows with all 24 v0.2 endpoints.tsv columns preserved.';
COMMENT ON TABLE source_annotations IS
    'Lossless source-specific fields in JSONB; prediction_annotation never changes endpoint evidence.';
COMMENT ON TABLE assets IS
    'Registered, checksum-pinned assets served through the same-origin Range proxy.';

COMMIT;
